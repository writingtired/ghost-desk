import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {DatabaseSync} from 'node:sqlite';
import {createDesktopReader} from '../desktop.mjs';
const home=fs.mkdtempSync(path.join(os.tmpdir(),'ghost-desk-test-'));
const desk=path.join(home,'AppData/Local/Claude-Data/package/claude-code-sessions/account/org'),registry=path.join(home,'.claude/sessions');
const ag=path.join(home,'.gemini/antigravity');
for(const folder of [desk,registry,ag]) fs.mkdirSync(folder,{recursive:true});
let now=Date.now(),running=true;
const host='local_'+randomUUID(),cli=randomUUID(),conversation=randomUUID();
const read=createDesktopReader({home,clock:()=>now,isAlive:pid=>running&&pid===1234});
const write=(dir,name,obj)=>fs.writeFileSync(path.join(dir,name),JSON.stringify(obj));
const worker={pid:1234,entrypoint:'claude-desktop',hostSessionId:host,sessionId:cli};
write(desk,host+'.json',{sessionId:host,title:'Piano score',lastActivityAt:now,completedTurns:2,cliSessionId:cli});
write(registry,'1234.json',{...worker,status:'busy',updatedAt:now});
const excluded='local_'+randomUUID();
write(registry,'777.json',{...worker,pid:777,entrypoint:'cli',hostSessionId:excluded,status:'waiting'});
const db=new DatabaseSync(path.join(ag,'conversation_summaries.db'));
db.exec('CREATE TABLE conversation_summaries(conversation_id TEXT,title TEXT,status TEXT,killed INTEGER,not_fully_idle INTEGER,last_modified_time TEXT,parent_conversation_id TEXT)');
const insert=db.prepare('INSERT INTO conversation_summaries VALUES(?,?,?,?,?,?,?)');
insert.run(conversation,'Arrange quartet','CASCADE_RUN_STATUS_IDLE',0,0,new Date(now).toISOString(),'');
insert.run(randomUUID(),'Subtask','CASCADE_RUN_STATUS_RUNNING',0,0,new Date(now).toISOString(),conversation);
const next=()=>{now+=2000;return read().sessions;};
let rows=next();assert.equal(rows.length,2);assert.equal(rows[0].id,'claude-desktop/'+host);
assert.equal(rows[0].state,'working');assert.equal(rows[1].state,'finished');
for(const [status,target] of [['waiting','attention'],['busy','working'],['idle','finished']]){
  write(registry,'1234.json',{...worker,status,updatedAt:now});
  assert.equal(next()[0].state,target);
}
running=false;assert.equal(next()[0].state,'unknown');
db.prepare('UPDATE conversation_summaries SET not_fully_idle=1 WHERE conversation_id=?').run(conversation);
assert.equal(next()[1].state,'working');
const logs=path.join(ag,'brain',conversation,'.system_generated/logs');
fs.mkdirSync(logs,{recursive:true});
write(logs,'transcript.jsonl',{type:'ASK_USER',status:'WAITING'});
assert.equal(next()[1].state,'attention');
write(logs,'transcript.jsonl',{type:'OTHER',status:'WAITING'});
assert.equal(next()[1].state,'working');
db.prepare('UPDATE conversation_summaries SET killed=1 WHERE conversation_id=?').run(conversation);
assert.equal(next()[1].state,'stopped');
insert.run(randomUUID(),'Arrange quartet expanded','CASCADE_RUN_STATUS_IDLE',0,0,new Date(now-2*86400000).toISOString(),'');
assert.equal(next()[1].uniqueTitle,false);
db.close();
fs.rmSync(home,{recursive:true,force:true});
console.log('Passed desktop discovery, separate host and worker IDs, waiting/resume/finish, stale workers, background activity, explicit input waits, stopped runs, nested session exclusion, and ambiguous title handling.');
