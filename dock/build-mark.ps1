# The same 16-pixel mark drives the tray icon, web badge, dock and CYD.
$ErrorActionPreference='Stop'
Add-Type -AssemblyName System.Drawing
$root=Split-Path -Parent $PSScriptRoot
$mark=@(
'                ',
' MM             ',
' MM     MMMM    ',
' MM   MMMMMMMM  ',
' MM  MMMMMMMMMM ',
' MM MMMMMMMMMMM ',
' MM MMWWWMWWWMM ',
' MM MMDWWMDWWMM ',
' MM MMDWWMDWWMM ',
' MM MMMMMMMMMMM ',
' MM MMMMMMMMMMM ',
' MM MMMMMMMMMMM ',
' MM MM MMMM MMM ',
' MM M   MM   MM ',
' MM             ',
'                ')
$colors=@{M=[Drawing.ColorTranslator]::FromHtml('#9DE1C5');W=[Drawing.Color]::White;D=[Drawing.ColorTranslator]::FromHtml('#162B32')}
$images=@()
foreach($size in 16,32,48,64,128,256){
    $bitmap=New-Object Drawing.Bitmap($size,$size)
    $g=[Drawing.Graphics]::FromImage($bitmap)
    $scale=$size/16
    for($y=0;$y -lt 16;$y++){
        for($x=0;$x -lt 16;$x++){
            $key=[string]$mark[$y][$x]
            if($colors.ContainsKey($key)){
                $brush=New-Object Drawing.SolidBrush($colors[$key])
                $g.FillRectangle($brush,[int]($x*$scale),[int]($y*$scale),[int]$scale,[int]$scale)
                $brush.Dispose()
            }
        }
    }
    $mem=New-Object IO.MemoryStream
    $bitmap.Save($mem,[Drawing.Imaging.ImageFormat]::Png)
    $images+=,@{size=$size;bytes=$mem.ToArray()}
    if($size -eq 256){[IO.File]::WriteAllBytes((Join-Path $root 'ghost-mark.png'),$mem.ToArray())}
    $g.Dispose();$bitmap.Dispose();$mem.Dispose()
}
$out=New-Object IO.BinaryWriter([IO.File]::Create((Join-Path $PSScriptRoot 'ghost.ico')))
try{
    $out.Write([uint16]0);$out.Write([uint16]1);$out.Write([uint16]$images.Count)
    $offset=6+16*$images.Count
    foreach($image in $images){
        $out.Write([byte]($image.size%256));$out.Write([byte]($image.size%256))
        $out.Write([uint16]0);$out.Write([uint16]1);$out.Write([uint16]32)
        $out.Write([uint32]$image.bytes.Length);$out.Write([uint32]$offset);$offset+=$image.bytes.Length
    }
    foreach($image in $images){$out.Write([byte[]]$image.bytes)}
}finally{$out.Dispose()}
$rows=($mark|ForEach-Object {'  "'+$_+'"'}) -join ",`n"
[IO.File]::WriteAllText((Join-Path $root 'hardware/GhostBoard/brand.h'),"#pragma once`n// Generated by dock/build-mark.ps1.`nstatic const char brandPixels[16][17]={`n$rows`n};`n")
